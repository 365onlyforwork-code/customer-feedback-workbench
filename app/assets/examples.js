function makeProject(name, prefix, products, channels, rules, records) {
  const rows = records.map(([text, product, channel, rating, tags = []], index) => ({
    id: `${prefix}-${String(index + 1).padStart(3, "0")}`,
    text,
    date: new Date(Date.UTC(2026, 10, 21 - ((index * 7) % 31))).toISOString().slice(0, 10),
    product: products[product],
    channel: channels[channel],
    rating: String(rating),
    tags,
  }));
  return { name, rows, rules };
}

